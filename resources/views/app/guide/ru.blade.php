        <li><b>Чёрный список</b> — при добавлении ребёнка, заявки или сотрудника совпадение телефона/свидетельства даёт предупреждение. Чтобы продолжить, нужны право «обход чёрного списка» и причина; это записывается в журнал.</li>
        <li><b>Заявки</b> — дата следующего звонка, ответственный; заявки старше 24 часов показываются красным на главной; при отказе причина обязательна; таблица конверсии по источникам.</li>
