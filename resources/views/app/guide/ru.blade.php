<section id="faq" data-guide>
    <h2>Частые вопросы</h2>
    <h3>Не вижу нужный раздел в меню</h3>
    <p>Либо у вашей должности нет этого права (проверьте Настройки → «Должности»), либо раздел скрыт в Настройки → «Разделы», либо его нет в вашем тарифе.</p>
    <h3>Родитель заплатил сразу за несколько месяцев</h3>
    <p>Внесите всю сумму. Баланс ребёнка будет положительным, и ежемесячные начисления будут покрываться из него.</p>
    <h3>Ребёнок ходит в основную группу и в кружок</h3>
    <p>Запишите его в кружок на странице кружка. Оплата попадёт на тот же баланс ребёнка отдельной строкой.</p>
    <h3>Как сменить язык?</h3>
    <p>Переключатель RU / UZ находится вверху справа на каждой странице.</p>
