    <h2>С чего начать</h2>
    <p>Первые шаги занимают 10–15 минут. Идите по порядку:</p>
    <ol>
        <li><b>Данные детского сада</b> — Настройки → «Данные сада»: название, телефон, адрес, логотип.</li>
        <li><b>Должности</b> — Настройки → «Должности»: создайте должности (воспитатель, кассир, бухгалтер…) и отметьте галочками, что может делать каждая из них.</li>
        <li><b>Группы</b> — раздел «Группы»: название, месячная стоимость, возраст, вместимость.</li>
        <li><b>Сотрудники</b> — раздел «Сотрудники»: выберите должность, укажите зарплату. Если сотруднику нужен вход в систему — включите «Право входа в систему».</li>
        <li><b>Дети</b> — раздел «Дети»: данные ребёнка и родителя, группа. Начисление за месяц произойдёт автоматически.</li>
        <li><b>Настройки оплаты</b> — Настройки → «Оплата детей»: способ начисления, скидка братьям и сёстрам, включение карты/банка.</li>
    </ol>
    <div class="callout"><p>Ненужный раздел можно скрыть: Настройки → «Разделы». Данные не удаляются, раздел можно включить в любой момент.</p></div>
</section>

