<section id="desk" data-guide>
    <h2>Касса и Финансы</h2>
    <p>Это два разных учёта. Они специально разделены, чтобы у директора были «чистые» деньги, а у кассира — дневная выручка.</p>
    <table class="t">
        <tr><th></th><th>Касса</th><th>Финансы (счёт директора)</th></tr>
        <tr><td>Кто работает</td><td>Кассир, администратор</td><td>Директор, бухгалтер</td></tr>
        <tr><td>Что здесь</td><td>Оплаты от родителей, мелкие расходы из кассы, передача денег директору</td><td>Деньги, принятые директором, расходы, доходы, зарплата, переводы между счетами</td></tr>
    </table>
    <h3>Как деньги попадают из Кассы в Финансы</h3>
    <ol>
        <li>Кассир принимает оплату от родителя: раздел «Касса» → «Принять оплату». Деньги остаются в кассе.</li>
        <li>В конце дня кассир нажимает «Передать директору» и указывает сумму.</li>
        <li>Директор видит запрос в разделе «Финансы» → «Деньги из кассы» и нажимает «Деньги принял» (или «Отклонить» с причиной).</li>
        <li>Только после этого сумма уходит из кассы и появляется на счёте директора. Пока директор не подтвердил, деньги считаются находящимися в кассе.</li>
    </ol>
    <p>Оплаты картой и банком могут требовать подтверждения (Настройки → «Финансы»): кассир или бухгалтер сверяет поступление и подтверждает.</p>
    <div class="callout warn"><p>Оплату нельзя «удалить». Ошибочную оплату отменяют или возвращают, и это остаётся в журнале.</p></div>
</section>

<section id="roles" data-guide>
    <h2>Должности и права доступа</h2>
    <p>Должности создаёт сам директор: Настройки → «Должности» → «Новая должность». Для каждой должности галочками отмечаются права: что можно смотреть, а что менять.</p>
    <ol>
        <li>Создайте должность (например, «Методист») и отметьте права. Кнопки «Все» и «Ничего» помогают отметить сразу весь блок.</li>
        <li>При добавлении сотрудника выберите его должность.</li>
        <li>Если сотруднику нужен вход в систему, включите «Право входа в систему», введите телефон и пароль. Права будут такими, как отмечены у его должности.</li>
        <li>Изменили права должности — они сразу меняются у всех сотрудников с этой должностью.</li>
    </ol>
    <p>Должности без права входа (повар, уборщица) нужны только для учёта и зарплаты. Должность «Директор» всегда имеет все права. Нельзя удалить должность, на которой есть сотрудники.</p>
</section>

<section id="payroll" data-guide>
    <h2>Зарплата: способы расчёта</h2>
    <table class="t">
        <tr><th>Способ</th><th>Как считается</th></tr>
        <tr><td><b>Фиксированная</b></td><td>Каждый месяц одинаковый оклад.</td></tr>
        <tr><td><b>По посещаемости</b></td><td>Дневная ставка × количество отработанных дней. Если ставка не указана, берётся оклад ÷ рабочие дни.</td></tr>
        <tr><td><b>Смешанная</b></td><td>Оклад + надбавка за каждого ребёнка в группах, к которым прикреплён сотрудник.</td></tr>
    </table>
    <div class="example"><p><b>Пример «смешанная».</b> Оклад 3 000 000, в группе воспитателя 15 детей, надбавка 50 000 за ребёнка → 3 000 000 + 15 × 50 000 = 3 750 000 сум.</p></div>
    <p><b>Когда доступна смешанная?</b> Это возможность тарифа Premium. Если у вас другой тариф, а она нужна, обратитесь в поддержку — доступ можно открыть отдельно. Способ можно задать для всего сада (Настройки → «Зарплата») или для отдельного сотрудника в его карточке.</p>
    <p>Если включена посещаемость сотрудников, за опоздания может вычитаться штраф (размер задаётся в настройках).</p>
</section>

<section id="sms" data-guide>
    <h2>SMS-уведомления</h2>
    <p>SMS отправляются через ваш аккаунт Eskiz. Тексты сообщений нужно согласовать с Eskiz (раздел SMS → шаблоны → «Отправить на проверку»). Пока шаблон не одобрен, сообщения не уходят.</p>
    <ul>
        <li>Для каждого события (оплата, долг, день рождения…) включите отправку и выберите шаблон.</li>
        <li>Чтобы SMS уходили, на сервере должен работать обработчик очереди (<code>php artisan queue:work</code>).</li>
    </ul>
</section>

<section id="plan" data-guide>
    <h2>Подписка и баланс</h2>
    <ul>
        <li>Новый сад получает <b>14 дней бесплатно</b>. После этого система переходит в режим «только просмотр» — данные сохраняются.</li>
        <li>Тарифы: 1, 3 и 12 месяцев. Пополнить баланс можно через Payme или по реквизитам карты с отправкой чека.</li>
        <li>За 3 дня до окончания приходит напоминание. Подписка не списывается автоматически: по окончании срока система переходит в режим «только просмотр», а для продолжения директор пополняет баланс и сам выбирает тариф.</li>
        <li>Если подписка не продлена более 90 дней, данные могут быть удалены — перед этим вас предупредят.</li>
    </ul>
</section>

