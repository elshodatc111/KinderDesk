        <tr><td><b>Пропорционально</b></td><td>Если ребёнок пришёл в середине месяца, списывается только за оставшиеся рабочие дни.</td></tr>
        <tr><td><b>Ежедневно (по посещаемости)</b></td><td>Цена группы делится на рабочие дни месяца — получается цена одного дня. Списывается только за дни, когда ребёнок отмечен «пришёл». Начисление за прошлый месяц происходит в выбранный день следующего месяца.</td></tr>
