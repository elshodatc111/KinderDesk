<section id="kids" data-guide>
    <h2>Дети</h2>
    <ul>
        <li><b>Баланс ребёнка</b>: плюс — предоплата, минус — долг. Он складывается из оплат и начислений.</li>
        <li><b>Индивидуальная цена</b> в карточке ребёнка заменяет цену группы.</li>
        <li><b>Перевод в другую группу</b> сохраняет историю. Начисление пересчитывается по тому, когда ребёнок перешёл.</li>
        <li><b>Архив</b>: ребёнок уходит из списка, история и долги сохраняются.</li>
        <li>Родители получают SMS об оплате и долге (если включено в разделе SMS).</li>
    </ul>
</section>

<section id="clubs" data-guide>
    <h2>Кружки</h2>
    <p>Кружок — отдельная платная услуга (английский, рисование, шахматы…). Для каждого кружка вы задаёте преподавателя, расписание и цену, а список участников собирается отдельно.</p>
    <ul>
        <li><b>Раз в месяц</b> — фиксированная сумма в месяц на каждого записанного ребёнка. Списывается 1-го числа и при записи.</li>
        <li><b>За занятие</b> — сумма за каждое занятие. Вы отмечаете, кто пришёл, и списывается только за присутствовавших.</li>
    </ul>
    <p>Оплата за кружок идёт с баланса ребёнка отдельной строкой, поэтому видно, сколько за основную группу, а сколько за кружок. Родитель вносит одну сумму через кассу.</p>
</section>

<section id="attendance" data-guide>
    <h2>Посещаемость</h2>
    <p>Воспитатель открывает «Посещаемость», выбирает группу и дату и отмечает: пришёл / не пришёл / болен. Без интернета отметки сохраняются на телефоне и отправляются при появлении связи.</p>
    <ul>
        <li>Субботнюю группу можно отметить только в субботу.</li>
        <li>Один и тот же ребёнок может быть отмечен в разных группах в один день (например, утром и вечером).</li>
        <li>Пока отметки не сохранены, кнопка «Сохранить» подсвечена.</li>
    </ul>
</section>

<section id="billing" data-guide>
    <h2>Оплата детей: способы начисления</h2>
    <p>Выберите способ в Настройки → «Оплата детей» → «Способ начисления».</p>
    <table class="t">
        <tr><th>Способ</th><th>Как считается</th></tr>
